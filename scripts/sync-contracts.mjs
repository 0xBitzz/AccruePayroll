// Copies matching compiled ABIs and a confirmed deployment into the web app.
// Use BROADCAST_FILE for a specific run; CHAIN_ID defaults to LitVM LiteForge (4441).
import { readFileSync, writeFileSync, existsSync, renameSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const chainId = Number(process.env.CHAIN_ID ?? 4441);
if (!Number.isSafeInteger(chainId) || chainId < 1) throw new Error("CHAIN_ID must be a positive integer.");

const artifactOf = (name) =>
  JSON.parse(readFileSync(join(root, `contracts/out/${name}.sol/${name}.json`), "utf8"));
const artifacts = { payroll: artifactOf("AccruePayroll"), lusd: artifactOf("LitUSD") };
const broadcast = process.env.BROADCAST_FILE
  ? resolve(process.env.BROADCAST_FILE)
  : join(root, `contracts/broadcast/Deploy.s.sol/${chainId}/run-latest.json`);
if (!existsSync(broadcast)) throw new Error("No deployment record found. Deploy the contracts before syncing.");

const run = JSON.parse(readFileSync(broadcast, "utf8"));
if (Number(run.chain) !== chainId) throw new Error(`Deployment chain ${run.chain} does not match CHAIN_ID ${chainId}.`);
if (!Array.isArray(run.transactions) || !Array.isArray(run.receipts) || !run.receipts.length || run.pending?.length)
  throw new Error("Deployment has missing receipts or pending transactions. Finish it before syncing.");

const addressOf = (value, name) => {
  if (typeof value !== "string" || !/^0x[0-9a-fA-F]{40}$/.test(value) || /^0x0{40}$/i.test(value))
    throw new Error(`${name} has no valid deployed address.`);
  return value;
};
const receiptOf = (tx) => {
  if (typeof tx.hash !== "string" || !/^0x[0-9a-fA-F]{64}$/.test(tx.hash))
    throw new Error(`Missing or invalid transaction hash for ${tx.contractName}.`);
  addressOf(tx.contractAddress, tx.contractName);
  const receipt = run.receipts.find((r) => r.transactionHash?.toLowerCase() === tx.hash?.toLowerCase());
  if (!receipt || BigInt(receipt.status ?? 0) !== 1n) throw new Error(`Missing or failed receipt for ${tx.contractName}.`);
  if (receipt.contractAddress?.toLowerCase() !== tx.contractAddress?.toLowerCase())
    throw new Error(`Receipt address does not match ${tx.contractName}.`);
  return receipt;
};
const normalizeHex = (value) => value.toLowerCase().replace(/^0x/, "");
const validateCreation = (tx, artifact) => {
  const receipt = receiptOf(tx);
  const data = tx.transaction?.input ?? tx.transaction?.data;
  // Both deployed contracts have no constructor arguments, so creation bytecode must match exactly.
  if (typeof data !== "string" || !artifact.bytecode?.object || normalizeHex(data) !== normalizeHex(artifact.bytecode.object))
    throw new Error(`Compiled ${tx.contractName} differs from the deployment. Redeploy before syncing its ABI.`);
  return receipt;
};

const payrollTx = run.transactions.find((tx) => tx.transactionType === "CREATE" && tx.contractName === "AccruePayroll");
if (!payrollTx) throw new Error("Deployment record has no AccruePayroll creation.");
const payrollReceipt = validateCreation(payrollTx, artifacts.payroll);
const tokenTx = run.transactions.find((tx) => tx.transactionType === "CREATE" && tx.contractName === "LitUSD");
if (tokenTx) validateCreation(tokenTx, artifacts.lusd);
const validateReturn = (name, tx) => {
  const returned = run.returns?.[name]?.value;
  if (returned !== undefined && tx && addressOf(returned, name).toLowerCase() !== tx.contractAddress.toLowerCase())
    throw new Error(`Script return for ${name} does not match its creation receipt.`);
};
validateReturn("payroll", payrollTx);
validateReturn("lusd", tokenTx);

const deployBlock = Number(BigInt(payrollReceipt.blockNumber));
if (!Number.isSafeInteger(deployBlock) || deployBlock < 0) throw new Error("Invalid deployment block.");
const deployment = {
  payroll: addressOf(payrollTx.contractAddress, "AccruePayroll"),
  // Deploy.s.sol returns the token even when it was reused rather than created in this run.
  lusd: addressOf(tokenTx?.contractAddress ?? run.returns?.lusd?.value ?? process.env.LUSD, "LitUSD"),
  deployBlock,
};

const out = `// Generated by scripts/sync-contracts.mjs — do not edit by hand.
export const deployment = {
  payroll: ${JSON.stringify(deployment.payroll)} as \`0x\${string}\` | null,
  lusd: ${JSON.stringify(deployment.lusd)} as \`0x\${string}\` | null,
  deployBlock: ${deployment.deployBlock} as number | null,
} as const;

export const payrollAbi = ${JSON.stringify(artifacts.payroll.abi, null, 2)} as const;

export const lusdAbi = ${JSON.stringify(artifacts.lusd.abi, null, 2)} as const;
`;
const target = join(root, "web/src/lib/generated.ts");
writeFileSync(`${target}.tmp`, out);
renameSync(`${target}.tmp`, target);
console.log("Synced confirmed contracts →", deployment);
